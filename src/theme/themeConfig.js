export const THEME_OPTIONS = Object.values(THEME_PRESETS);

export const getThemePreset = (themeId) =>
  THEME_PRESETS[themeId] || THEME_PRESETS[DEFAULT_THEME_ID];

export const normalizeThemeId = (themeId) =>
  THEME_PRESETS[themeId] ? themeId : DEFAULT_THEME_ID;

export const normalizeThemeMode = (value) => {
  if (value === "light" || value === "dark" || value === "system") {
    return value;
  }

  return "system";
};
